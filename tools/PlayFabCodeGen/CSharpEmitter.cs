using System.Text;

namespace PlayFabCodeGen;

/// <summary>
/// Generates C# source files from parsed Swagger API groups.
/// </summary>
public sealed class CSharpEmitter
{
    private readonly CodeGenConfig _config;

    public CSharpEmitter(CodeGenConfig config)
    {
        _config = config;
    }

    /// <summary>
    /// Generates a C# models file for the given API group.
    /// Returns null when the group contains no types (nothing to emit).
    /// </summary>
    public string? EmitModels(ApiGroup group)
    {
        if (group.Types.Count == 0)
        {
            return null;
        }

        var sb = new StringBuilder();
        EmitFileHeader(sb, includeJsonUsing: true);
        sb.AppendLine($"namespace {_config.Output.Namespace}.{group.Name};");
        sb.AppendLine();

        foreach (var typeDef in group.Types.OrderBy(t => t.Name))
        {
            if (typeDef.IsEnum)
            {
                EmitEnum(sb, typeDef);
            }
            else
            {
                EmitClass(sb, typeDef);
            }

            sb.AppendLine();
        }

        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    /// <summary>
    /// Generates an API metadata file that maps operation IDs to paths, types, and request/response type names.
    /// </summary>
    public string EmitApiMetadata(List<ApiGroup> groups)
    {
        var sb = new StringBuilder();
        EmitFileHeader(sb, includeJsonUsing: false);
        sb.AppendLine($"namespace {_config.Output.Namespace};");
        sb.AppendLine();

        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Registry of all PlayFab API endpoints, auto-generated from Swagger specs.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class PlayFabApiMetadata");
        sb.AppendLine("{");

        // Emit ApiEndpoint record
        sb.AppendLine("    public sealed record ApiEndpoint(");
        sb.AppendLine("        string Group,");
        sb.AppendLine("        string OperationId,");
        sb.AppendLine("        string Path,");
        sb.AppendLine("        string Tag,");
        sb.AppendLine("        string Description,");
        sb.AppendLine("        string? RequestType,");
        sb.AppendLine("        string? ResponseType);");
        sb.AppendLine();

        // Emit all endpoints as a static array
        sb.AppendLine("    public static readonly ApiEndpoint[] AllEndpoints =");
        sb.AppendLine("    [");

        foreach (var group in groups.OrderBy(g => g.Name))
        {
            foreach (var op in group.Operations.OrderBy(o => o.OperationId))
            {
                var reqType = op.RequestTypeName != null ? $"\"{op.RequestTypeName}\"" : "null";
                var respType = op.ResponseTypeName != null ? $"\"{op.ResponseTypeName}\"" : "null";
                sb.AppendLine($"        new(\"{group.Name}\", \"{op.OperationId}\", \"{op.Path}\", \"{EscapeCSharpString(op.Tag)}\", \"{EscapeCSharpString(Truncate(op.Description, 200))}\", {reqType}, {respType}),");
            }
        }

        sb.AppendLine("    ];");

        // Emit group names
        sb.AppendLine();
        sb.AppendLine("    public static readonly string[] ApiGroups =");
        sb.AppendLine("    [");
        foreach (var group in groups.OrderBy(g => g.Name))
        {
            sb.AppendLine($"        \"{group.Name}\",");
        }

        sb.AppendLine("    ];");

        sb.AppendLine("}");

        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    private void EmitFileHeader(StringBuilder sb, bool includeJsonUsing)
    {
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// This file was auto-generated by PlayFabCodeGen from PlayFab Swagger specs.");
        sb.AppendLine("// Do not edit manually. Re-run the code generator to update.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        if (_config.Preferences.NullableReferenceTypes)
        {
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
        }

        if (includeJsonUsing)
        {
            sb.AppendLine("using System.Text.Json.Serialization;");
            sb.AppendLine();
        }
    }

    private void EmitEnum(StringBuilder sb, TypeDefinition typeDef)
    {
        if (_config.Preferences.GenerateXmlDocs && !string.IsNullOrEmpty(typeDef.Description))
        {
            EmitXmlDoc(sb, typeDef.Description, indent: "");
        }

        sb.AppendLine("[JsonConverter(typeof(JsonStringEnumConverter))]");
        sb.AppendLine($"public enum {typeDef.Name}");
        sb.AppendLine("{");

        foreach (var val in typeDef.EnumValues)
        {
            sb.AppendLine($"    {val},");
        }

        sb.AppendLine("}");
    }

    private void EmitClass(StringBuilder sb, TypeDefinition typeDef)
    {
        if (_config.Preferences.GenerateXmlDocs && !string.IsNullOrEmpty(typeDef.Description))
        {
            EmitXmlDoc(sb, typeDef.Description, indent: "");
        }

        sb.AppendLine($"public sealed class {typeDef.Name}");
        sb.AppendLine("{");

        foreach (var prop in typeDef.Properties)
        {
            if (_config.Preferences.GenerateXmlDocs && !string.IsNullOrEmpty(prop.Description))
            {
                EmitXmlDoc(sb, prop.Description, indent: "    ");
            }

            sb.AppendLine($"    [JsonPropertyName(\"{prop.Name}\")]");

            var csType = ResolveCSharpType(prop);
            sb.AppendLine($"    public {csType} {prop.Name} {{ get; set; }}");
            sb.AppendLine();
        }

        sb.AppendLine("}");
    }

    private string ResolveCSharpType(PropertyDefinition prop)
    {
        var nullable = _config.Preferences.NullableReferenceTypes;

        string baseType;
        if (prop.TypeRef != null)
        {
            baseType = prop.TypeRef;
        }
        else if (prop.PrimitiveType != null)
        {
            baseType = MapPrimitiveType(prop.PrimitiveType, prop.Format);
        }
        else
        {
            baseType = "object";
        }

        if (prop.IsDictionary)
        {
            var valType = baseType == "object" ? "object" : baseType;
            var dictType = $"Dictionary<string, {valType}>";
            return nullable ? $"{dictType}?" : dictType;
        }

        if (prop.IsArray)
        {
            var listType = $"List<{baseType}>";
            return nullable ? $"{listType}?" : listType;
        }

        // Value types: nullable when not required
        if (IsValueType(baseType))
        {
            return prop.IsRequired ? baseType : $"{baseType}?";
        }

        // Reference types: always nullable for generated deserialization models
        return nullable ? $"{baseType}?" : baseType;
    }

    private static string MapPrimitiveType(string swaggerType, string? format)
    {
        return swaggerType switch
        {
            "string" when format == "date-time" => "DateTime",
            "string" => "string",
            "integer" when format == "int64" => "long",
            "integer" => "int",
            "number" when format == "float" => "float",
            "number" when format == "double" => "double",
            "number" => "double",
            "boolean" => "bool",
            "object" => "object",
            _ => "object",
        };
    }

    private static bool IsValueType(string csType)
    {
        return csType is "int" or "long" or "float" or "double" or "bool" or "DateTime";
    }

    private static void EmitXmlDoc(StringBuilder sb, string description, string indent)
    {
        var escaped = EscapeXmlString(description);

        // Handle multi-line descriptions
        var lines = escaped.Split('\n');
        sb.AppendLine($"{indent}/// <summary>");
        foreach (var line in lines)
        {
            sb.AppendLine($"{indent}/// {line.TrimEnd()}");
        }

        sb.AppendLine($"{indent}/// </summary>");
    }

    private static string EscapeXmlString(string s)
    {
        return s.Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;")
                .Replace("\"", "&quot;");
    }

    private static string EscapeCSharpString(string s)
    {
        return s.Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\n", "\\n")
                .Replace("\r", "");
    }

    private static string Truncate(string s, int maxLength)
    {
        if (s.Length <= maxLength)
        {
            return s;
        }

        return s[..(maxLength - 3)] + "...";
    }
}
